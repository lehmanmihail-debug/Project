#!/bin/bash

# Скрипт, который запрашивает два числа и выводит их сумму

echo "Введите первое число:"
read num1

echo "Введите второе число:"
read num2

# Проверка, что введены числа
if ! [[ "$num1" =~ ^-?[0-9]+$ ]] || ! [[ "$num2" =~ ^-?[0-9]+$ ]]; then
    echo "Ошибка: введите целые числа!"
    exit 1
fi

sum=$((num1 + num2))
echo "Сумма $num1 + $num2 = $sum"