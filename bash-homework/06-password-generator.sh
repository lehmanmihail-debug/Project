#!/bin/bash

# Скрипт, который генерирует случайный пароль длиной 8 символов

# Можно указать длину как аргумент или использовать 8 по умолчанию
length=${1:-8}

if ! [[ "$length" =~ ^[0-9]+$ ]] || [ "$length" -lt 1 ]; then
    echo "Ошибка: длина должна быть положительным числом!"
    exit 1
fi

# Генерация пароля с использованием /dev/urandom
password=$(tr -dc 'A-Za-z0-9!@#$%^&*()_+' < /dev/urandom | head -c "$length")

echo "Сгенерированный пароль (длина $length): $password"