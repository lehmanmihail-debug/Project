#!/bin/bash

# Скрипт, который определяет, является ли число четным или нечетным

echo "Введите число:"
read number

# Проверка, что введено число
if ! [[ "$number" =~ ^-?[0-9]+$ ]]; then
    echo "Ошибка: введите целое число!"
    exit 1
fi

if [ $((number % 2)) -eq 0 ]; then
    echo "Число $number - ЧЁТНОЕ"
else
    echo "Число $number - НЕЧЁТНОЕ"
fi